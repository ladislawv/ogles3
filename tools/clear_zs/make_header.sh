#!/bin/bash
# Compiles the program ogles2 clears depth and stencil with where a
# framebuffer has a 32-bit float or integer colour target (a glClear of
# depth or stencil confined by the scissor box or write masks, or after
# draws; draw.c): it writes no colour, so no colour write of the wrong
# width reaches those targets (GLES3 plan stage B item 10). Writes it into
# ogles2/clear_zs_v3dp.h as a .v3dp image the library loads from memory.
# Run in WSL after the host v3dglslc changes (its .v3dp records the Mesa
# commit the loader checks):  bash tools/clear_zs/make_header.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
V3DGLSLC=${V3DGLSLC:-$HOME/ogles2-build/v3dglslc/host/v3dglslc}
W=$(mktemp -d)
cp "$HERE/clear_zs.vert" "$HERE/clear_zs.frag" "$W/"
(cd "$W" && "$V3DGLSLC" -o . clear_zs.vert clear_zs.frag > log.txt 2>&1) || { cat "$W/log.txt"; exit 1; }
python3 - "$W/clear_zs-clear_zs.v3dp" "$REPO/ogles2/clear_zs_v3dp.h" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
out = ["/* Generated by tools/clear_zs/make_header.sh from clear_zs.vert and",
       " * clear_zs.frag: do not edit. The program draw.c clears depth and",
       " * stencil with where a colour target is 32-bit float or integer: it",
       " * writes no colour. A .v3dp image (v3dp/FORMAT.md). */",
       "static const UBYTE clear_zs_v3dp[%d] = {" % len(data)]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("%s: %d bytes" % (sys.argv[2], len(data)))
PY
rm -rf "$W"
